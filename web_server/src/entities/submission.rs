use crate::entities::{ProblemObject, UserObject};
use chrono::{DateTime, Local};
use postgres_types::{FromSql, ToSql};
use serde::Serialize;

/// Judge result  
/// It is provied by exit status of `test_runner` and `judge_server`.
#[derive(Debug, Copy, Clone, Serialize, ToSql, FromSql)]
#[postgres(name = "judgeresult")]
pub enum JudgeResult {
    /// ACcepted
    AC = 0,
    /// Wrong Answer
    WA,
    /// Wrong Compile Error
    WC,
    /// Assembly Error
    AE,
    /// Linker Error
    LE,
    /// Runtime Error
    RE,
    /// Time Limit Exceeded
    TLE,
    /// the submit is pending.
    Pending,
    /// The judge failed due to system error.
    SystemError,
}

/// Architecture chosen by the submitter at submit time.
/// Serializes as the database enum labels `x8664` / `riscv`.
#[derive(Debug, Copy, Clone, Serialize, ToSql, FromSql)]
#[postgres(name = "arch")]
#[allow(non_camel_case_types)]
pub enum Arch {
    /// x86_64
    x8664,
    /// RISC-V.
    riscv,
}

/// Submission data
#[derive(Serialize)]
#[allow(non_snake_case)]
pub struct SubmissionObject {
    /// Submission id.
    id: i32,
    /// Submission time.
    time: DateTime<Local>,
    /// Submitted assembly.
    asm: String,
    /// Did submited as `compile error`.
    is_ce: bool,
    /// Error line number.
    error_line_number: Option<i32>,
    /// Judge result.
    result: JudgeResult,
    /// Error message generated by assembler or linker or runtime.
    error_message: String,
    /// Architecture chosen by the submitter.
    arch: Arch,
    /// Submitted user.
    user: UserObject,
    /// Problem.
    problem: ProblemObject,
}

/// Getting submission result
#[derive(Serialize)]
#[allow(non_snake_case)]
pub struct Submission {
    /// Getting submission successeed or not.
    /// * `ok` - successeed
    /// * `ng` - failed
    status: String,
    /// Submissions
    submission: SubmissionObject,
    /// Error message.
    errorMessage: Option<String>,
}

/// Getting submission result submitted by specified user.
#[derive(Serialize)]
#[allow(non_snake_case)]
pub struct UserSubmissions {
    /// Getting submission that submitted by specified user successeed or not.
    /// * `ok` - successeed
    /// * `ng` - failed
    status: String,
    /// Submissions
    #[serde(rename = "items")]
    submissions: Vec<SubmissionObject>,
    /// Error message.
    errorMessage: Option<String>,
}

impl SubmissionObject {
    /// Return new `SubmissionObject`.
    pub fn new(
        id: i32,
        time: DateTime<Local>,
        asm: String,
        error_message: String,
        is_ce: bool,
        error_line_number: Option<i32>,
        result: JudgeResult,
        arch: Arch,
        user: UserObject,
        problem: ProblemObject,
    ) -> Self {
        SubmissionObject {
            id,
            time,
            asm,
            error_message,
            is_ce,
            error_line_number,
            result,
            arch,
            user,
            problem,
        }
    }

    /// Return dummy `SubmissionObject`.
    pub fn dummy() -> Self {
        SubmissionObject {
            id: 0,
            time: Local::now(),
            asm: String::new(),
            error_message: String::new(),
            is_ce: false,
            error_line_number: None,
            result: JudgeResult::SystemError,
            arch: Arch::x8664,
            user: UserObject::dummy(),
            problem: ProblemObject::dummy(),
        }
    }
}

impl Submission {
    pub fn owner_id(&self) -> i32 {
        self.submission.user.id()
    }

    pub fn forbidden() -> Self {
        let mut response = Self::error();
        response.status = "forbidden".to_string();
        response.errorMessage =
            Some("You cannot view this submission during the contest".to_string());
        response
    }
    /// Return successeed response.
    pub fn new(
        id: i32,
        time: DateTime<Local>,
        asm: String,
        error_message: String,
        is_ce: bool,
        error_line_number: Option<i32>,
        result: JudgeResult,
        arch: Arch,
        user: UserObject,
        problem: ProblemObject,
    ) -> Self {
        Submission {
            status: "ok".to_string(),
            submission: SubmissionObject::new(
                id,
                time,
                asm,
                error_message,
                is_ce,
                error_line_number,
                result,
                arch,
                user,
                problem,
            ),
            errorMessage: None,
        }
    }

    /// Return error response.
    pub fn error() -> Self {
        Submission {
            status: "ng".to_string(),
            submission: SubmissionObject::dummy(),
            errorMessage: Some("couldn't find a user".to_string()),
        }
    }
}

impl UserSubmissions {
    /// Return successeed response.
    pub fn new(
        status: String,
        submissions: Vec<SubmissionObject>,
        error_message: Option<String>,
    ) -> Self {
        UserSubmissions {
            status,
            submissions,
            errorMessage: error_message,
        }
    }

    /// Return error response.
    pub fn error(status: &str, msg: &str) -> Self {
        UserSubmissions {
            status: status.to_string(),
            submissions: Vec::new(),
            errorMessage: Some(msg.to_string()),
        }
    }
}
